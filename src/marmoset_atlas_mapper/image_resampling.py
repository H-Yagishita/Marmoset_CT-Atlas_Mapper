from __future__ import annotations

import SimpleITK as sitk


def resample_atlas_to_target(
    atlas_image: sitk.Image,
    target_image: sitk.Image,
    target_to_atlas_forward: sitk.Transform,
    interpolation: str,
) -> sitk.Image:
    if interpolation == "nearest":
        interpolator = sitk.sitkNearestNeighbor
        pixel_id = atlas_image.GetPixelID()
    elif interpolation == "linear":
        interpolator = sitk.sitkLinear
        pixel_id = sitk.sitkFloat32
    else:
        raise ValueError(f"Unsupported interpolation: {interpolation}")
    # Resample requests an output(Target) -> input(Atlas) transform, which is
    # exactly the forward consensus transform generated by this application.
    component_count = atlas_image.GetNumberOfComponentsPerPixel()
    if component_count == 1:
        return sitk.Resample(
            atlas_image,
            target_image,
            target_to_atlas_forward,
            interpolator,
            0.0,
            pixel_id,
        )
    # SimpleITK's 3D resampler does not accept all vector pixel types used by
    # the RGB Nissl/Myelin volumes. Resample scalar channels and re-compose.
    components = []
    for index in range(component_count):
        component = sitk.VectorIndexSelectionCast(atlas_image, index, sitk.sitkFloat32)
        components.append(
            sitk.Resample(
                component,
                target_image,
                target_to_atlas_forward,
                interpolator,
                0.0,
                sitk.sitkFloat32,
            )
        )
    return sitk.Compose(components)


def resample_target_to_atlas(
    target_image: sitk.Image,
    atlas_reference: sitk.Image,
    atlas_to_target: sitk.Transform,
    convergence_mask: sitk.Image,
) -> tuple[sitk.Image, sitk.Image]:
    """Resample Target CT into Atlas geometry and zero unconverged inverse regions."""
    mapped = sitk.Resample(
        target_image,
        atlas_reference,
        atlas_to_target,
        sitk.sitkLinear,
        0.0,
        sitk.sitkFloat32,
    )
    native_mask = sitk.Resample(
        convergence_mask,
        atlas_reference,
        sitk.Transform(3, sitk.sitkIdentity),
        sitk.sitkNearestNeighbor,
        0,
        sitk.sitkUInt8,
    )
    return sitk.Mask(mapped, native_mask), native_mask
